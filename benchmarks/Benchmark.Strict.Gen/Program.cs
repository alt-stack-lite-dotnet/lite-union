static string Value(Combo c, int i) => $"global::Bench.{c.Set.Name}.C{i}";
static string Types(Combo c) => string.Join(", ", c.Cases.Select(t => t.Fqn));

// The adapter around one union type. Create(i) builds the union of case i, matchBody is the body of Match(u).
static string Adapter(Combo c, string unionType, Func<int, string> create, string matchBody, string size, string? equal = null)
{
    var sb = new StringBuilder();
    sb.Append($"public readonly struct Ad_{c.Name} : IAdapter<{unionType}>\n{{\n");
    sb.Append($"    public static int Cases => {c.N};\n");
    sb.Append($"    public static int ByteSize => {size};\n");
    sb.Append($"    public static {unionType} Create(int index) => index switch\n    {{\n");
    for (var i = 0; i < c.N; i++)
    {
        sb.Append($"        {i} => {create(i)},\n");
    }

    sb.Append("        _ => throw new System.ArgumentOutOfRangeException(nameof(index)),\n    };\n");
    sb.Append($"    public static long Match({unionType} u)\n    {{\n{matchBody}\n    }}\n");
    sb.Append("    public static long Expected(int index) => index switch\n    {\n");
    for (var i = 0; i < c.N; i++)
    {
        sb.Append($"        {i} => global::Bench.Sums.Of({Value(c, i)}),\n");
    }

    sb.Append("        _ => throw new System.ArgumentOutOfRangeException(nameof(index)),\n    };\n");
    var comparison = equal ?? $"System.Collections.Generic.EqualityComparer<{unionType}>.Default.Equals(a, b)";
    sb.Append($"    public static bool Equal({unionType} a, {unionType} b) => {comparison};\n}}\n");
    return sb.ToString();
}

// "x0 => Sums.Of(x0), x1 => ..." for the libraries that take one function per case.
static string Lambdas(Combo c, string accessor = "")
    => string.Join(", ", Enumerable.Range(0, c.N).Select(i => $"x{i} => global::Bench.Sums.Of(x{i}{accessor})"));

static string StructSize(string unionType) => $"System.Runtime.CompilerServices.Unsafe.SizeOf<{unionType}>()";

static Emitted? Lite(Combo c, string layout, bool kind)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    sb.Append($"[global::Lite.Union.Union<{Types(c)}>(Layout = global::Lite.Union.UnionLayout.{layout})]\npublic partial struct {u} {{ }}\n\n");
    string body;
    if (kind)
    {
        var cases = string.Join("\n", c.Cases.Select(t => $"            case {u}.CaseKind.{t.Leaf}: return global::Bench.Sums.Of(u.Get{t.Leaf}());"));
        body = $"        switch (u.Kind)\n        {{\n{cases}\n            default: return 0;\n        }}";
    }
    else
    {
        body = $"        return u.Match({Lambdas(c)});";
    }

    sb.Append(Adapter(c, u, i => $"({u}){Value(c, i)}", body, StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

static Emitted? OneOf(Combo c)
{
    var u = $"global::OneOf.OneOf<{Types(c)}>";
    return new Emitted(Adapter(c, u, i => $"{u}.FromT{i}({Value(c, i)})", $"        return u.Match({Lambdas(c)});", StructSize(u)), u);
}

static Emitted? Dunet(Combo c)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    sb.Append($"[global::Dunet.Union]\npublic partial record {u}\n{{\n");
    for (var i = 0; i < c.N; i++)
    {
        sb.Append($"    partial record C{i}({c.Cases[i].Fqn} Value);\n");
    }

    sb.Append("}\n\n");
    sb.Append(Adapter(c, u, i => $"new {u}.C{i}({Value(c, i)})", $"        return u.Match({Lambdas(c, ".Value")});", "System.IntPtr.Size"));
    return new Emitted(sb.ToString(), u);
}

static Emitted? UnionTypes(Combo c)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    foreach (var t in c.Cases)
    {
        sb.Append($"[global::N.SourceGenerators.UnionTypes.UnionType(typeof({t.Fqn}))]\n");
    }

    sb.Append($"public partial struct {u} {{ }}\n\n");
    sb.Append(Adapter(c, u, i => $"({u}){Value(c, i)}", $"        return u.Match<long>({Lambdas(c)});", StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

static Emitted? DotVariant(Combo c)
{
    var u = $"U_{c.Name}";
    var parameters = string.Join(", ", c.Cases.Select((t, i) => $"{t.Fqn} c{i}"));
    var sb = new StringBuilder();
    sb.Append($"[global::dotVariant.Variant]\npublic readonly partial struct {u}\n{{\n    static partial void VariantOf({parameters});\n}}\n\n");
    sb.Append(Adapter(c, u, i => $"new {u}({Value(c, i)})", $"        return u.Visit({Lambdas(c)}, () => 0L);", StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

static Emitted? StructUnion(Combo c)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    sb.Append($"[global::StructUnion.StructUnion]\npublic readonly partial struct {u}\n{{\n");
    for (var i = 0; i < c.N; i++)
    {
        sb.Append($"    public static partial {u} V{i}({c.Cases[i].Fqn} value);\n");
    }

    sb.Append("}\n\n");
    sb.Append(Adapter(c, u, i => $"{u}.V{i}({Value(c, i)})", $"        return u.Match({Lambdas(c)});", StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

static Emitted? SumSharp(Combo c, bool objectStorage)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    for (var i = 0; i < c.N; i++)
    {
        sb.Append($"[global::SumSharp.UnionCase(\"C{i}\", typeof({c.Cases[i].Fqn}))]\n");
    }

    if (objectStorage)
    {
        sb.Append("[global::SumSharp.UnionStorage(Strategy: global::SumSharp.UnionStorageStrategy.OneObject)]\n");
    }

    sb.Append($"public partial struct {u} {{ }}\n\n");
    var lambdas = string.Join(", ", Enumerable.Range(0, c.N).Select(i => $"C{i}: x{i} => global::Bench.Sums.Of(x{i})"));
    sb.Append(Adapter(c, u, i => $"{u}.C{i}({Value(c, i)})", $"        return u.Match({lambdas});", StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

// A union written by hand, the best a person would do: values overlapped with a tag, or a tag and one object.
// Only for the two sets where that is simple.
static Emitted? Reference(Combo c)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    if (c.Set.Name == "Values")
    {
        sb.Append($"[System.Runtime.InteropServices.StructLayout(System.Runtime.InteropServices.LayoutKind.Explicit)]\npublic struct {u} : System.IEquatable<{u}>\n{{\n");
        sb.Append("    [System.Runtime.InteropServices.FieldOffset(0)] public byte Tag;\n");
        for (var i = 0; i < c.N; i++)
        {
            sb.Append($"    [System.Runtime.InteropServices.FieldOffset(8)] public {c.Cases[i].Fqn} V{i};\n");
        }

        var compare = string.Join("\n", Enumerable.Range(0, c.N).Select(i => $"            case {i + 1}: return V{i}.Equals(other.V{i});"));
        sb.Append($"    public bool Equals({u} other)\n    {{\n        if (Tag != other.Tag) return false;\n        switch (Tag)\n        {{\n{compare}\n            default: return true;\n        }}\n    }}\n");
        sb.Append($"    public override bool Equals(object? obj) => obj is {u} o && Equals(o);\n    public override int GetHashCode() => Tag;\n");
        for (var i = 0; i < c.N; i++)
        {
            sb.Append($"    public static {u} Make{i}() {{ {u} r = default; r.Tag = {i + 1}; r.V{i} = {Value(c, i)}; return r; }}\n");
        }

        sb.Append("}\n\n");
        var cases = string.Join("\n", Enumerable.Range(0, c.N).Select(i => $"            case {i + 1}: return global::Bench.Sums.Of(u.V{i});"));
        var body = $"        switch (u.Tag)\n        {{\n{cases}\n            default: return 0;\n        }}";
        sb.Append(Adapter(c, u, i => $"{u}.Make{i}()", body, StructSize(u)));
        return new Emitted(sb.ToString(), u);
    }

    if (c.Set.Name == "Refs")
    {
        sb.Append($"public struct {u} : System.IEquatable<{u}>\n{{\n    public byte Tag;\n    public object? Obj;\n");
        sb.Append($"    public bool Equals({u} other) => Tag == other.Tag && Equals(Obj, other.Obj);\n");
        sb.Append($"    public override bool Equals(object? obj) => obj is {u} o && Equals(o);\n    public override int GetHashCode() => Tag;\n}}\n\n");
        var cases = string.Join("\n", Enumerable.Range(0, c.N).Select(i => $"            case {i + 1}: return global::Bench.Sums.Of(({c.Cases[i].Fqn})u.Obj!);"));
        var body = $"        switch (u.Tag)\n        {{\n{cases}\n            default: return 0;\n        }}";
        sb.Append(Adapter(c, u, i => $"new {u} {{ Tag = {i + 1}, Obj = {Value(c, i)} }}", body, StructSize(u)));
        return new Emitted(sb.ToString(), u);
    }

    return null;
}

// ----- part B: .NET 11, the case is taken out with the C# 15 switch over the union -----

static string PatternBody(Combo c)
{
    var arms = string.Join(",\n            ", Enumerable.Range(0, c.N).Select(i => $"{c.Cases[i].Fqn} x{i} => global::Bench.Sums.Of(x{i})"));
    return $"        return u switch\n        {{\n            {arms},\n        }};";
}

static Emitted? NativeB(Combo c)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    sb.Append($"public union {u}({Types(c)});\n\n");
    sb.Append(Adapter(c, u, i => $"({u}){Value(c, i)}", PatternBody(c), StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

static Emitted? LiteB(Combo c, string layout)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    sb.Append($"[global::Lite.Union.Union<{Types(c)}>(Layout = global::Lite.Union.UnionLayout.{layout})]\npublic partial struct {u} {{ }}\n\n");
    sb.Append(Adapter(c, u, i => $"({u}){Value(c, i)}", PatternBody(c), StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

static Emitted? NonboxingB(Combo c)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    var typeofs = string.Join(", ", c.Cases.Select(t => $"typeof({t.Fqn})"));
    sb.Append($"[global::NonboxingUnion.NonBoxingUnion({typeofs})]\npublic partial struct {u} {{ }}\n\n");
    sb.Append(Adapter(c, u, i => $"({u}){Value(c, i)}", PatternBody(c), StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

// With NativeUnion StructUnion generates a case type per variant (Union.Cases.V0, ...); the C# 15 switch matches those.
static Emitted? StructUnionB(Combo c)
{
    var u = $"U_{c.Name}";
    var sb = new StringBuilder();
    sb.Append($"[global::StructUnion.StructUnion(NativeUnion = true)]\npublic readonly partial struct {u}\n{{\n");
    for (var i = 0; i < c.N; i++)
    {
        sb.Append($"    public static partial {u} V{i}({c.Cases[i].Fqn} value);\n");
    }

    sb.Append("}\n\n");
    var arms = string.Join(",\n            ", Enumerable.Range(0, c.N).Select(i => $"{u}.Cases.V{i} x{i} => global::Bench.Sums.Of(x{i}.Value)"));
    var body = $"        return u switch\n        {{\n            {arms},\n        }};";
    sb.Append(Adapter(c, u, i => $"{u}.V{i}({Value(c, i)})", body, StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

// On .NET 11 SumSharp makes a wrapper type for every case ("record struct <CaseName>(<T> Value)") in the namespace of the
// union, and the C# 15 switch matches those wrappers. Case names must therefore be unique across all the unions of the project.
static Emitted? SumSharpB(Combo c, bool objectStorage)
{
    var u = $"U_{c.Name}";
    var name = (int i) => $"{c.Name}_{i}";
    var sb = new StringBuilder();
    for (var i = 0; i < c.N; i++)
    {
        sb.Append($"[global::SumSharp.UnionCase(\"{name(i)}\", typeof({c.Cases[i].Fqn}))]\n");
    }

    if (objectStorage)
    {
        sb.Append("[global::SumSharp.UnionStorage(Strategy: global::SumSharp.UnionStorageStrategy.OneObject)]\n");
    }

    sb.Append($"public partial struct {u} {{ }}\n\n");
    var arms = string.Join(",\n            ", Enumerable.Range(0, c.N).Select(i => $"global::Bench.{name(i)} x{i} => global::Bench.Sums.Of(x{i}.Value)"));
    var body = $"        return u switch\n        {{\n            {arms},\n        }};";
    sb.Append(Adapter(c, u, i => $"{u}.{name(i)}({Value(c, i)})", body, StructSize(u)));
    return new Emitted(sb.ToString(), u);
}

record CaseType(string Fqn, string Leaf);
record Emitted(string Code, string UnionType);
record Built(Combo Combo, string UnionType);
record Set(string Name, CaseType[] Types);
record Lib(string Id, string Display, Func<Combo, Emitted?> Emit);

record Combo(Lib Lib, Set Set, int N)
{
    public string Name => $"{Lib.Id}_{Set.Name}_{N}";
    public CaseType[] Cases => Set.Types.Take(N).ToArray();
}
