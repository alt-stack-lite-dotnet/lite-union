Directory.CreateDirectory(outDir);
foreach (var old in Directory.GetFiles(outDir, "*.g.cs"))
{
    File.Delete(old);
}

// Combinations that do not work (found by the self-check, kept in unsupported.csv with the reason) are not generated:
// an unloadable struct in the assembly would stop BenchmarkDotNet from scanning it.
var unsupportedFile = Path.Combine(outDir, "..", "unsupported.csv");
var unsupported = File.Exists(unsupportedFile)
    ? File.ReadLines(unsupportedFile).Skip(1).Select(line => line.Split(',')[0]).ToHashSet()
    : new HashSet<string>();

var combos = new List<Built>();
foreach (var lib in libs)
{
    var text = new StringBuilder();
    text.Append("// <auto-generated/> by Benchmark.Strict.Gen\n#nullable enable\n#pragma warning disable\nnamespace Bench;\n\n");
    foreach (var set in sets)
    {
        foreach (var n in sizes)
        {
            var combo = new Combo(lib, set, n);
            if (unsupported.Contains(combo.Name))
            {
                continue;
            }

            var code = lib.Emit(combo);
            if (code is null)
            {
                continue; // the library cannot express this combination
            }

            text.Append(code.Code).Append('\n');
            combos.Add(new Built(combo, code.UnionType));
        }
    }

    File.WriteAllText(Path.Combine(outDir, "Adapters." + lib.Id + ".g.cs"), text.ToString(), new UTF8Encoding(false));
}

// One benchmark class per combination: a concrete class gets its own report file and a readable name.
var workloads = new StringBuilder("// <auto-generated/> by Benchmark.Strict.Gen\n#nullable enable\nnamespace Bench;\n\n");
foreach (var built in combos)
{
    workloads.Append($"public class W_{built.Combo.Name} : Workloads<{built.UnionType}, Ad_{built.Combo.Name}> {{ }}\n");
}

File.WriteAllText(Path.Combine(outDir, "Workloads.g.cs"), workloads.ToString(), new UTF8Encoding(false));

var registry = new StringBuilder("// <auto-generated/> by Benchmark.Strict.Gen\n#nullable enable\nnamespace Bench;\n\npublic static class Registry\n{\n");
registry.Append("    public static readonly (string Name, string Lib, string Set, int Cases, System.Func<CheckResult> Verify)[] All =\n    {\n");
foreach (var built in combos)
{
    var combo = built.Combo;
    registry.Append($"        (\"{combo.Name}\", \"{combo.Lib.Id}\", \"{combo.Set.Name}\", {combo.N}, () => Checks.Verify<{built.UnionType}, Ad_{combo.Name}>()),\n");
}

registry.Append("    };\n}\n");
File.WriteAllText(Path.Combine(outDir, "Registry.g.cs"), registry.ToString(), new UTF8Encoding(false));

// The classes to hand to BenchmarkDotNet. A union the CLR cannot load (one library produces such structs for some sets)
// makes its class unloadable too, so each type is asked for separately and the ones that fail are left out.
var types = new StringBuilder("// <auto-generated/> by Benchmark.Strict.Gen\n#nullable enable\nnamespace Bench;\n\npublic static class WorkloadTypes\n{\n");
types.Append("    private static readonly System.Func<System.Type>[] All =\n    {\n");
foreach (var built in combos)
{
    types.Append($"        () => typeof(W_{built.Combo.Name}),\n");
}

types.Append("    };\n\n    public static System.Type[] Loadable()\n    {\n        var list = new System.Collections.Generic.List<System.Type>();\n");
types.Append("        foreach (var get in All)\n        {\n            try { list.Add(get()); } catch (System.Exception) { }\n        }\n\n        return list.ToArray();\n    }\n}\n");
File.WriteAllText(Path.Combine(outDir, "WorkloadTypes.g.cs"), types.ToString(), new UTF8Encoding(false));
Console.WriteLine($"{combos.Count} combinations written to {Path.GetFullPath(outDir)}");

