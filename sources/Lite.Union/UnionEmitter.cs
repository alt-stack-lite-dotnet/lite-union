#nullable enable

using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Lite.Union;

internal static class AttributeSource
{
    public const string Namespace = "Lite.Union";
    public const int MaxCases = 16;

    /// <summary>UnionAttribute&lt;T1..Tn&gt; for n = 2..16. Any type can be a case.</summary>
    public static string Build()
    {
        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n");
        builder.Append("namespace ").Append(Namespace).Append('\n');
        builder.Append("{\n");
        builder.Append("    /// <summary>How the cases of a Union struct are laid out in memory.</summary>\n");
        builder.Append("    internal enum UnionLayout\n");
        builder.Append("    {\n");
        builder.Append("        /// <summary>Values overlap with values and references with references. Smallest, no allocations.</summary>\n");
        builder.Append("        Overlap = 0,\n");
        builder.Append("        /// <summary>Every case has a field of its own. Largest, no allocations, nothing clever.</summary>\n");
        builder.Append("        Flat = 1,\n");
        builder.Append("        /// <summary>Everything in one object field: references as is, values boxed. Smallest, allocates on creation.</summary>\n");
        builder.Append("        Boxed = 2,\n");
        builder.Append("    }\n\n");
        builder.Append("    /// <summary>What to do with a case that cannot be overlapped (Layout = Overlap only).</summary>\n");
        builder.Append("    internal enum UnionFallback\n");
        builder.Append("    {\n");
        builder.Append("        /// <summary>A field of its own for each such case. No allocations, the struct is larger. The default.</summary>\n");
        builder.Append("        Field = 0,\n");
        builder.Append("        /// <summary>All such cases share one object field, values are boxed. Smaller, allocates on creation.</summary>\n");
        builder.Append("        Boxed = 1,\n");
        builder.Append("    }\n\n");

        for (var arity = 2; arity <= MaxCases; arity++)
        {
            var parameters = Enumerable.Range(1, arity).Select(i => "T" + i).ToArray();

            builder.Append("    [global::System.AttributeUsage(global::System.AttributeTargets.Struct, Inherited = false, AllowMultiple = false)]\n");
            builder.Append("    internal sealed class UnionAttribute<").Append(string.Join(", ", parameters)).Append("> : global::System.Attribute\n");
            builder.Append("    {\n");
            builder.Append("        public UnionLayout Layout { get; set; }\n");
            builder.Append("        public UnionFallback Fallback { get; set; }\n");
            builder.Append("    }\n\n");
        }

        builder.Append("}\n");
        return builder.ToString();
    }
}

internal static class UnionEmitter
{
    private const string Sys = "global::System.";
    private const string Interop = "global::System.Runtime.InteropServices.";
    private const string Compiler = "global::System.Runtime.CompilerServices.";

    // Layout: the struct is { byte kind; __Values values; __Refs refs }.
    //
    // Every case is split into leaves: unmanaged ones go to __Values, GC-tracked references go to __Refs.
    // Inside __Values all cases overlap at offset 0 (values over values), inside __Refs they overlap too
    // (references over references). A reference never shares bytes with a number, which is what the CLR
    // demands. A struct mixing both (struct { int; string }) is split field by field and put back together
    // in Read{Case}() with [UnsafeAccessor], so the cost is a few field copies and no allocations.
    public static string Emit(UnionModel model)
    {
        var w = new CodeWriter();
        var name = model.Name;
        var cases = model.Cases;
        var ro = model.IsReadOnly ? "" : "readonly ";
        var hasValues = cases.Any(c => c.Values.Length > 0);
        var hasRefs = cases.Any(c => c.Refs.Length > 0);
        var hasOpaque = cases.Any(c => c.IsOpaque);
        var hasBoxed = cases.Any(c => c.IsBoxed);

        // Layout = Boxed keeps no tag: the whole struct is one object field.
        var tagless = model.Layout == 2;

        w.Line("// <auto-generated/>");
        w.Line("#nullable enable");
        w.Line("#pragma warning disable CS0649, CS0169");
        w.Line();

        if (model.Namespace is not null)
        {
            w.Open("namespace " + model.Namespace);
        }

        foreach (var container in model.Containers)
        {
            w.Open("partial " + container.Keyword + " " + container.Name);
        }

        var needsUnsafe = cases.Any(c => c.NeedsUnsafe);
        if (model.NativeUnion)
        {
            w.Line("[" + Compiler + "Union]");
        }

        w.Open((model.IsReadOnly ? "readonly " : "") + (needsUnsafe ? "unsafe " : "") + "partial struct " + name
            + " : " + Sys + "IEquatable<" + name + ">" + (model.NativeUnion ? ", " + Compiler + "IUnion" : ""));

        // Kind enum. 0 is reserved for default(T).
        w.Open("public enum CaseKind : byte");
        w.Line("Uninitialized = 0,");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line(cases[i].Name + " = " + (i + 1) + ",");
        }

        w.Close();
        w.Line();

        // Per-case leaf structs.
        for (var i = 0; i < cases.Length; i++)
        {
            EmitLeafStruct(w, "__V" + i, cases[i].Values);
            EmitLeafStruct(w, "__R" + i, cases[i].Refs);
        }

        EmitPayload(w, "__Values", "__V", cases, c => c.Values.Length > 0);
        EmitPayload(w, "__Refs", "__R", cases, c => c.Refs.Length > 0);

        // Cases that cannot be split (generic structs mixing references and values) are stored as they are.
        if (hasOpaque)
        {
            w.Open("private struct __Opaque");
            for (var i = 0; i < cases.Length; i++)
            {
                if (cases[i].IsOpaque)
                {
                    w.Line("public " + cases[i].Type + " o" + i + ";");
                }
            }

            w.Close();
            w.Line();
        }

        // Accessors for leaves behind private fields.
        for (var i = 0; i < cases.Length; i++)
        {
            EmitAccessors(w, i, "v", cases[i].Values);
            EmitAccessors(w, i, "r", cases[i].Refs);
        }

        if (tagless)
        {
            // No tag: the case is told by the type of the object, the more specific cases first.
            // A null object is "no value": the same as default, and a null reference case.
            w.Open("private " + ro + "byte _kind");
            w.Open("get");
            w.Line("var o = _obj;");
            w.Line("if (o is null) return 0;");
            foreach (var index in model.CheckOrder)
            {
                w.Line("if (o is " + cases[index].TestType + ") return " + (index + 1) + ";");
            }

            w.Line("return 0;");
            w.Close();
            w.Close();
        }
        else
        {
            w.Line("private readonly byte _kind;");
        }

        if (hasValues)
        {
            w.Line("private readonly __Values _values;");
        }

        if (hasRefs)
        {
            w.Line("private readonly __Refs _refs;");
        }

        if (hasOpaque)
        {
            w.Line("private readonly __Opaque _opaque;");
        }

        if (hasBoxed)
        {
            w.Line("private readonly object? _obj;");
        }

        w.Line();

        var ctorParameters = new List<string>();
        if (!tagless)
        {
            ctorParameters.Add("byte kind");
        }

        if (hasValues)
        {
            ctorParameters.Add("__Values values");
        }

        if (hasRefs)
        {
            ctorParameters.Add("__Refs refs");
        }

        if (hasOpaque)
        {
            ctorParameters.Add("__Opaque opaque");
        }

        if (hasBoxed)
        {
            ctorParameters.Add("object? obj");
            if (tagless)
            {
                // Keeps the private constructor apart from the public constructor of an object case (C# 15 unions).
                ctorParameters.Add("bool boxed");
            }
        }

        w.Open("private " + name + "(" + string.Join(", ", ctorParameters) + ")");
        if (!tagless)
        {
            w.Line("_kind = kind;");
        }

        if (hasValues)
        {
            w.Line("_values = values;");
        }

        if (hasRefs)
        {
            w.Line("_refs = refs;");
        }

        if (hasOpaque)
        {
            w.Line("_opaque = opaque;");
        }

        if (hasBoxed)
        {
            w.Line("_obj = obj;");
        }

        w.Close();
        w.Line();

        w.Line("public " + ro + "CaseKind Kind => (CaseKind)_kind;");
        w.Line("public " + ro + "bool IsUninitialized => _kind == 0;");
        w.Line();

        if (model.NativeUnion)
        {
            EmitNativeUnion(w, name, ro, cases);
        }

        // Per-case members.
        for (var i = 0; i < cases.Length; i++)
        {
            var @case = cases[i];
            var type = @case.Type;
            var caseName = @case.Name;
            var tag = i + 1;

            w.Open("public static " + name + " From" + caseName + "(" + type + " value)");
            if (hasValues)
            {
                w.Line("__Values values = default;");
            }

            if (hasRefs)
            {
                w.Line("__Refs refs = default;");
            }

            if (hasOpaque)
            {
                w.Line("__Opaque opaque = default;");
                if (@case.IsOpaque)
                {
                    w.Line("opaque.o" + i + " = value;");
                }
            }

            for (var j = 0; j < @case.Values.Length; j++)
            {
                w.Line("values.c" + i + ".f" + j + " = " + LeafExpr(i, "v", j, @case.Values[j], "value") + ";");
            }

            for (var j = 0; j < @case.Refs.Length; j++)
            {
                w.Line("refs.c" + i + ".f" + j + " = " + LeafExpr(i, "r", j, @case.Refs[j], "value") + ";");
            }

            if (hasBoxed)
            {
                w.Line("object? obj = " + (@case.IsBoxed ? "value" : "null") + ";");
            }

            var ctorArguments = new List<string>();
            if (!tagless)
            {
                ctorArguments.Add(tag.ToString());
            }

            if (hasValues)
            {
                ctorArguments.Add("values");
            }

            if (hasRefs)
            {
                ctorArguments.Add("refs");
            }

            if (hasOpaque)
            {
                ctorArguments.Add("opaque");
            }

            if (hasBoxed)
            {
                ctorArguments.Add("obj");
                if (tagless)
                {
                    ctorArguments.Add("true");
                }
            }

            w.Line("return new " + name + "(" + string.Join(", ", ctorArguments) + ");");
            w.Close();
            w.Line();

            if (!@case.NoImplicit)
            {
                w.Line("public static implicit operator " + name + "(" + type + " value) => From" + caseName + "(value);");
                w.Line();
            }

            // Read{Case}: puts the case back together from its leaves.
            w.Open("private " + ro + type + " Read" + caseName + "()");
            // A case that is a single leaf (unmanaged type or reference type) is returned as is.
            var wholeValue = @case.Values.Length == 1 && @case.Refs.Length == 0 && @case.Values[0].Path.Length == 0;
            var wholeRef = @case.Refs.Length == 1 && @case.Values.Length == 0 && @case.Refs[0].Path.Length == 0;
            if (@case.IsBoxed)
            {
                w.Line("return (" + type + ")_obj!;");
            }
            else if (@case.IsOpaque)
            {
                w.Line("return _opaque.o" + i + ";");
            }
            else if (wholeValue || wholeRef)
            {
                w.Line("return " + (wholeValue ? "_values" : "_refs") + ".c" + i + ".f0;");
            }
            else
            {
                w.Line(type + " result = default;");
                for (var j = 0; j < @case.Values.Length; j++)
                {
                    w.Line(LeafExpr(i, "v", j, @case.Values[j], "result") + " = _values.c" + i + ".f" + j + ";");
                }

                for (var j = 0; j < @case.Refs.Length; j++)
                {
                    w.Line(LeafExpr(i, "r", j, @case.Refs[j], "result") + " = _refs.c" + i + ".f" + j + ";");
                }

                w.Line("return result;");
            }

            w.Close();
            w.Line();

            w.Line("public " + ro + "bool Is" + caseName + " => _kind == " + tag + ";");
            w.Line();

            w.Open("public " + ro + "bool TryGet" + caseName + "(out " + type + " value)");
            w.Open("if (_kind == " + tag + ")");
            w.Line("value = Read" + caseName + "();");
            w.Line("return true;");
            w.Close();
            w.Line("value = default!;");
            w.Line("return false;");
            w.Close();
            w.Line();

            w.Line("public " + ro + type + " Get" + caseName + "() => _kind == " + tag
                + " ? Read" + caseName + "() : throw WrongKind(CaseKind." + caseName + ");");
            w.Line();
        }

        w.Line("private " + ro + Sys + "InvalidOperationException WrongKind(CaseKind expected)");
        w.Line("    => new " + Sys + "InvalidOperationException(\"Expected \" + expected + \", but the value is \" + Kind + \".\");");
        w.Line();

        // Match / Switch.
        var funcs = string.Join(", ", cases.Select(c => Sys + "Func<" + c.Type + ", TMatchResult> on" + c.Name));
        w.Open("public " + ro + "TMatchResult Match<TMatchResult>(" + funcs + ")");
        w.Open("switch (_kind)");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("case " + (i + 1) + ": return on" + cases[i].Name + "(Read" + cases[i].Name + "());");
        }

        w.Line("default: throw new " + Sys + "InvalidOperationException(\"The value is uninitialized.\");");
        w.Close();
        w.Close();
        w.Line();

        var actions = string.Join(", ", cases.Select(c => Sys + "Action<" + c.Type + "> on" + c.Name));
        w.Open("public " + ro + "void Switch(" + actions + ")");
        w.Open("switch (_kind)");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("case " + (i + 1) + ": on" + cases[i].Name + "(Read" + cases[i].Name + "()); return;");
        }

        w.Line("default: throw new " + Sys + "InvalidOperationException(\"The value is uninitialized.\");");
        w.Close();
        w.Close();
        w.Line();

        // Equality. Compared per case through the case type's own Equals.
        w.Open("public " + ro + "bool Equals(" + name + " other)");
        w.Line("if (_kind != other._kind) return false;");
        w.Open("switch (_kind)");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("case " + (i + 1) + ": return " + Sys + "Collections.Generic.EqualityComparer<" + cases[i].Type
                + ">.Default.Equals(Read" + cases[i].Name + "(), other.Read" + cases[i].Name + "());");
        }

        w.Line("default: return true;");
        w.Close();
        w.Close();
        w.Line();

        w.Line("public " + ro + "override bool Equals(object? obj) => obj is " + name + " other && Equals(other);");
        w.Line();

        w.Open("public " + ro + "override int GetHashCode()");
        w.Open("switch (_kind)");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("case " + (i + 1) + ": return unchecked(_kind * 397 ^ " + Sys + "Collections.Generic.EqualityComparer<" + cases[i].Type
                + ">.Default.GetHashCode(Read" + cases[i].Name + "()!));");
        }

        w.Line("default: return _kind;");
        w.Close();
        w.Close();
        w.Line();

        w.Open("public " + ro + "override string ToString()");
        w.Open("switch (_kind)");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("case " + (i + 1) + ": return $\"" + cases[i].Name + "({Read" + cases[i].Name + "()})\";");
        }

        w.Line("default: return \"Uninitialized\";");
        w.Close();
        w.Close();
        w.Line();

        w.Line("public static bool operator ==(" + name + " left, " + name + " right) => left.Equals(right);");
        w.Line("public static bool operator !=(" + name + " left, " + name + " right) => !left.Equals(right);");

        w.Close(); // struct
        foreach (var _ in model.Containers)
        {
            w.Close();
        }

        if (model.Namespace is not null)
        {
            w.Close();
        }

        return w.ToString();
    }

    /// <summary>
    /// Members that make the struct a C# 15 union: a constructor per case, Value (boxes only when asked for),
    /// and the non-boxing access pattern (HasValue, TryGetValue), which the compiler prefers in pattern matching.
    /// A null reference or a null Nullable&lt;T&gt; counts as "no value", as the specification demands.
    /// </summary>
    private static void EmitNativeUnion(CodeWriter w, string name, string ro, EquatableArray<CaseInfo> cases)
    {
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("public " + name + "(" + cases[i].Type + " value) { this = From" + cases[i].Name + "(value); }");
        }

        w.Line();

        w.Open("public " + ro + "object? Value");
        w.Open("get");
        w.Open("switch (_kind)");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("case " + (i + 1) + ": return Read" + cases[i].Name + "();");
        }

        w.Line("default: return null;");
        w.Close();
        w.Close();
        w.Close();
        w.Line();

        w.Open("public " + ro + "bool HasValue");
        w.Open("get");
        w.Open("switch (_kind)");
        for (var i = 0; i < cases.Length; i++)
        {
            w.Line("case " + (i + 1) + ": return " + (cases[i].CanBeNull ? "Read" + cases[i].Name + "() is not null" : "true") + ";");
        }

        w.Line("default: return false;");
        w.Close();
        w.Close();
        w.Close();
        w.Line();

        for (var i = 0; i < cases.Length; i++)
        {
            w.Open("public " + ro + "bool TryGetValue(out " + cases[i].Type + " value)");
            w.Open("if (_kind == " + (i + 1) + ")");
            w.Line("value = Read" + cases[i].Name + "();");
            w.Line("return " + (cases[i].CanBeNull ? "value is not null" : "true") + ";");
            w.Close();
            w.Line("value = default!;");
            w.Line("return false;");
            w.Close();
            w.Line();
        }
    }

    private static void EmitLeafStruct(CodeWriter w, string structName, EquatableArray<LeafInfo> leaves)
    {
        if (leaves.Length == 0)
        {
            return;
        }

        w.Open("private struct " + structName);
        for (var j = 0; j < leaves.Length; j++)
        {
            w.Line("public " + leaves[j].Type + " f" + j + ";");
        }

        w.Close();
        w.Line();
    }

    private static void EmitPayload(
        CodeWriter w, string payloadName, string leafPrefix, EquatableArray<CaseInfo> cases, System.Func<CaseInfo, bool> has)
    {
        if (!cases.Any(has))
        {
            return;
        }

        w.Line("[" + Interop + "StructLayout(" + Interop + "LayoutKind.Explicit)]");
        w.Open("private struct " + payloadName);
        for (var i = 0; i < cases.Length; i++)
        {
            if (has(cases[i]))
            {
                w.Line("[" + Interop + "FieldOffset(0)] public " + leafPrefix + i + " c" + i + ";");
            }
        }

        w.Close();
        w.Line();
    }

    private static void EmitAccessors(CodeWriter w, int caseIndex, string kind, EquatableArray<LeafInfo> leaves)
    {
        for (var j = 0; j < leaves.Length; j++)
        {
            var path = leaves[j].Path;
            for (var k = 0; k < path.Length; k++)
            {
                var step = path[k];
                w.Line("[" + Compiler + "UnsafeAccessor(" + Compiler + "UnsafeAccessorKind.Field, Name = \"" + step.Field + "\")]");
                w.Line("private static extern ref " + step.FieldType + " " + AccessorName(caseIndex, kind, j, k) + "(ref " + step.Owner + " obj);");
                w.Line();
            }
        }
    }

    private static string AccessorName(int caseIndex, string kind, int leaf, int step)
        => "__A" + caseIndex + "_" + kind + leaf + "_" + step;

    /// <summary>Expression that reads or writes a leaf of <paramref name="variable"/> (a local that can be passed by ref).</summary>
    private static string LeafExpr(int caseIndex, string kind, int leafIndex, LeafInfo leaf, string variable)
    {
        var expr = variable;
        for (var k = 0; k < leaf.Path.Length; k++)
        {
            expr = AccessorName(caseIndex, kind, leafIndex, k) + "(ref " + expr + ")";
        }

        return expr;
    }

    private sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new();
        private int _indent;

        public void Line(string text = "")
        {
            if (text.Length > 0)
            {
                _builder.Append(' ', _indent * 4).Append(text);
            }

            _builder.Append('\n');
        }

        public void Open(string header)
        {
            Line(header);
            Line("{");
            _indent++;
        }

        public void Close()
        {
            _indent--;
            Line("}");
        }

        public override string ToString() => _builder.ToString();
    }
}
